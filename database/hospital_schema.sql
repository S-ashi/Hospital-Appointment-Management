CREATE TABLE PATIENT (
    PATIENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PATIENT_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(120) NOT NULL UNIQUE,
    PHONE VARCHAR2(15) NOT NULL
);

CREATE TABLE DOCTOR (
    DOCTOR_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DOCTOR_NAME VARCHAR2(100) NOT NULL,
    SPECIALIZATION VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(120) NOT NULL UNIQUE,
    CONSULTATION_FEE NUMBER(10,2) NOT NULL CHECK (CONSULTATION_FEE >= 0)
);

CREATE TABLE APPOINTMENT (
    APPOINTMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PATIENT_ID NUMBER NOT NULL,
    DOCTOR_ID NUMBER NOT NULL,
    APPOINTMENT_DATE DATE NOT NULL,
    APPOINTMENT_TIME VARCHAR2(8) NOT NULL,
    REASON VARCHAR2(500),
    STATUS VARCHAR2(20) DEFAULT 'BOOKED' NOT NULL,
    CONSTRAINT FK_APPT_PATIENT FOREIGN KEY (PATIENT_ID) REFERENCES PATIENT(PATIENT_ID),
    CONSTRAINT FK_APPT_DOCTOR FOREIGN KEY (DOCTOR_ID) REFERENCES DOCTOR(DOCTOR_ID),
    CONSTRAINT CK_APPT_STATUS CHECK (STATUS IN ('BOOKED', 'CANCELLED'))
);

